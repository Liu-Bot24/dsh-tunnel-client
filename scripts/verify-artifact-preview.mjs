// Disposable DSH replay fixture for real-browser image-click verification. No model calls.
import fs from 'node:fs/promises'
import os from 'node:os'
import path from 'node:path'
import { randomUUID } from 'node:crypto'
import { fileURLToPath } from 'node:url'
import readline from 'node:readline'
import spawn from 'cross-spawn'
import sharp from 'sharp'
import lifecycle from '../src/core/local-dsh-manager.cjs'

const project = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const root = await fs.realpath(await fs.mkdtemp(path.join(os.tmpdir(), 'dsh-preview-click-test-')))
const dshHome = path.join(root, 'home')
const workspace = path.join(root, 'artifacts')
const profile = path.join(dshHome, 'profiles', 'web')
const pluginTarget = path.join(profile, 'node_modules', 'dsh-plugin-artifact-preview')
const port = Number(process.argv[2] ?? 31986)
const manager = new lifecycle.LocalDshManager({
  executable: path.join(project, 'resources', 'dsh-runner', process.platform === 'win32' ? 'dsh.cmd' : 'dsh'),
  cwd: workspace,
  environment: { ...process.env, DSH_HOME: dshHome, DSH_TELEMETRY_DISABLED: '1' },
  noOpenSupported: true, startupTimeout: 60000, shutdownTimeout: 2000,
  spawnProcess(executable, args, options) {
    const child = spawn(executable, args, options)
    child.stderr.on('data', chunk => process.stderr.write(chunk))
    return child
  },
})

async function json(filename, value) {
  await fs.writeFile(filename, JSON.stringify(value, null, 2) + '\n')
}

function projectKey(cwd) {
  let result = ''
  let separator = false
  for (const char of cwd) {
    if ('/\\:'.includes(char)) {
      if (!separator) result += '-'
      separator = true
    } else {
      result += /^[A-Za-z0-9._-]$/u.test(char) ? char : '~' + char.charCodeAt(0).toString(16).toUpperCase().padStart(4, '0')
      separator = false
    }
  }
  return `--${result.replace(/^-+/u, '').slice(0, 251)}--`
}

try {
  await fs.mkdir(workspace, { recursive: true })
  await fs.mkdir(pluginTarget, { recursive: true })
  for (const entry of ['package.json', 'index.js', 'client.js', 'cordis.patch.yml', 'src']) {
    await fs.cp(path.join(project, 'plugins', 'artifact-preview', entry), path.join(pluginTarget, entry), { recursive: true })
  }
  await json(path.join(profile, 'package.json'), {
    name: 'preview-click-test', private: true,
    dsh: { profile: { bundles: ['@deepseek-ai/dsh-base', '@deepseek-ai/dsh-web-app', 'dsh-plugin-artifact-preview'] } },
    dependencies: { 'dsh-plugin-artifact-preview': `file:${path.join(project, 'plugins', 'artifact-preview')}` },
  })
  await fs.writeFile(path.join(profile, 'cordis.yml'), '[]\n')
  await fs.writeFile(path.join(profile, 'cordis.patch.yml'), `- id: session-persistence-jsonl\n  config:\n    root: ${JSON.stringify(path.join(dshHome, 'sessions'))}\n    compression: none\n`)
  const formats = ['png', 'jpg', 'jpeg', 'webp', 'gif', 'avif', 'svg', 'html']
  for (const [index, format] of formats.entries()) {
    const filename = `sample.${format}`
    const filePath = path.join(workspace, filename)
    if (format === 'svg') {
      await fs.writeFile(filePath, '<svg xmlns="http://www.w3.org/2000/svg" width="320" height="180"><rect width="320" height="180" fill="teal"/><text x="20" y="90" fill="white">SVG preview test</text></svg>')
    } else if (format === 'html') {
      await fs.writeFile(filePath, '<!doctype html><title>HTML preview test</title><h1>HTML preview test</h1>')
    } else {
      await sharp({ create: { width: 320, height: 180, channels: 3, background: '#287cad' } })
        .toFormat(format === 'jpg' ? 'jpeg' : format).toFile(filePath)
    }
    const id = `preview-click-${format}`
    const createdAt = Date.now() + index
    const callId = randomUUID()
    const args = JSON.stringify({ file_path: filePath, content: 'fixture generated by verification script' })
    const events = []
    const add = (type, data, extra = {}) => events.push({ type, seq: events.length, time: createdAt + events.length, data, ...extra })
    const message = (role, content, source) => ({ role, id: randomUUID(), content, source })
    add('turn/start', { turn: 1 })
    add('step/start', { turn: 1, step: 1 })
    add('user/message', message('user', [{ type: 'text', text: `Image click test ${format.toUpperCase()}` }], { kind: 'user' }), { surfaceOp: 'append' })
    add('assistant/message', { turn: 1, step: 1, message: message('assistant', [{ type: 'tool-call', id: callId, name: 'write', arguments: args }], { kind: 'model', provider: 'fixture', model: 'fixture' }) }, { surfaceOp: 'append' })
    add('tool/call', { turn: 1, step: 1, callId, name: 'write', arguments: args })
    add('tool/result', { turn: 1, step: 1, message: message('user', [{ type: 'tool-result', toolCallId: callId, content: [{ type: 'text', text: `Created ${filename}` }], isError: false }], { kind: 'tool', callId }), meta: { diffs: [] } }, { surfaceOp: 'append', sourceEventSeqs: [4] })
    add('step/end', { turn: 1, step: 1 })
    add('step/start', { turn: 1, step: 2 })
    add('assistant/message', { turn: 1, step: 2, message: message('assistant', [{ type: 'text', text: `Preview fixture ready: \`${filename}\`.` }], { kind: 'model', provider: 'fixture', model: 'fixture' }) }, { surfaceOp: 'append' })
    add('step/end', { turn: 1, step: 2 })
    add('turn/end', { turn: 1, reason: { kind: 'completed' } })
    const sessionDir = path.join(dshHome, 'sessions', projectKey(workspace), id)
    await fs.mkdir(sessionDir, { recursive: true })
    const header = { type: 'session', version: 0, id, createdAt, cwd: workspace, delegationDepth: 0, agentPreset: 'standard' }
    await fs.writeFile(path.join(sessionDir, 'session.jsonl'), [header, ...events].map(x => JSON.stringify(x)).join('\n') + '\n')
  }
  await manager.start(port)
  console.log(JSON.stringify({ ready: true, root, port, url: `http://127.0.0.1:${port}/?dsh_tunnel_preview=web`, formats }))
  const input = readline.createInterface({ input: process.stdin })
  const keepAlive = setInterval(() => {}, 1000)
  await new Promise(resolve => {
    input.once('line', resolve)
    input.once('close', resolve)
    process.once('SIGTERM', resolve)
    process.once('SIGINT', resolve)
  })
  clearInterval(keepAlive)
  input.close()
} finally {
  if (manager.hasOwnedProcess()) await manager.stop()
  await fs.rm(root, { recursive: true, force: true })
  console.log(JSON.stringify({ cleaned: true }))
}
